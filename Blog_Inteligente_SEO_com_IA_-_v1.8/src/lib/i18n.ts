export type LangCode = 'pt' | 'en' | 'es';

export function normalizeLang(lang: string | undefined | null): LangCode {
  if (lang === 'en' || lang === 'es') return lang;
  return 'pt';
}

export function getLocale(lang: string): string {
  const l = normalizeLang(lang);
  return l === 'en' ? 'en-US' : l === 'es' ? 'es-ES' : 'pt-BR';
}

export function htmlLang(lang: string): string {
  const l = normalizeLang(lang);
  return l === 'en' ? 'en' : l === 'es' ? 'es' : 'pt-BR';
}

export function formatDate(
  lang: string,
  date: string | Date,
  opts: Intl.DateTimeFormatOptions = { year: 'numeric', month: 'long', day: 'numeric' }
): string {
  const d = typeof date === 'string' ? new Date(date) : date;
  if (Number.isNaN(d.getTime())) return '';
  return d.toLocaleDateString(getLocale(lang), opts);
}

export function formatMoney(lang: string, cents: number, currency = 'BRL'): string {
  return (cents / 100).toLocaleString(getLocale(lang), { style: 'currency', currency });
}

