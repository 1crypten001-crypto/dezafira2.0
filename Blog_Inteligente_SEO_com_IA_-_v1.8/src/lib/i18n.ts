// Deep-merge extended admin UI dictionary (forms, pages, common actions)
function deepMergeAdmin(base: any, ...layers: any[]) {
  const out = { ...base };
  for (const layer of layers) {
    for (const [k, v] of Object.entries(layer || {})) {
      if (v && typeof v === 'object' && !Array.isArray(v) && typeof out[k] === 'object' && out[k] !== null) {
        out[k] = { ...out[k], ...v };
      } else {
        out[k] = v;
      }
    }
  }
  return out;
}

for (const lang of ['pt', 'en', 'es'] as LangCode[]) {
  translations[lang].admin = deepMergeAdmin(
    translations[lang].admin,
    adminExtra[lang],
    adminResidual[lang]
  );
}

export function t(lang: string, key: string, vars?: Record<string, string | number>): string {
  const currentLang = normalizeLang(lang);
  const keys = key.split('.');
  let result: any = translations[currentLang];

  for (const k of keys) {
    if (result && typeof result === 'object' && k in result) {
      result = result[k];
    } else {
      let fallback: any = translations.pt;
      for (const fk of keys) {
        fallback = fallback && typeof fallback === 'object' ? fallback[fk] : null;
      }
      result = fallback;
      break;
    }
  }

  if (typeof result !== 'string') return key;

  if (vars) {
    let str = result;
    for (const [vKey, vVal] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${vKey}\\}`, 'g'), String(vVal));
    }
    return str;
  }

  return result;
}

